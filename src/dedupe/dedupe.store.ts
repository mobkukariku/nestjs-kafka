export const DEDUPE_STORE = Symbol('DEDUPE_STORE');

/**
 * Трёхфазный контракт дедупликации.
 *
 * Порядок вызовов в консьюмере:
 *   claim()  — до обработки, ставит короткий in-flight TTL;
 *   commit() — после успешной обработки, продлевает TTL до основного;
 *   release() — на любом провальном пути, снимает клейм.
 *
 * Короткий TTL на этапе claim принципиален: если процесс упадёт между claim и
 * коммитом оффсета, запись протухнет сама и переотданное сообщение будет
 * обработано, а не отброшено как дубликат.
 */
export interface DedupeStore {
  /** true — клейм получен, обработка разрешена. false — событие уже в работе или обработано. */
  claim(eventId: string): Promise<boolean>;
  /** Пометить событие как окончательно обработанное (основной TTL). */
  commit(eventId: string): Promise<void>;
  /** Снять клейм, чтобы событие можно было переобработать или реплейнуть из DLQ. */
  release(eventId: string): Promise<void>;
}
